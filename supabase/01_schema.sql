drop table if exists lampiran, riwayat_barang_bukti, barang_bukti, perkara,
  lokasi_penyimpanan, kategori, pengguna cascade;
drop type if exists role_pengguna, status_akun, tahap_perkara, kondisi_barang,
  status_barang, jenis_riwayat, status_kembali, jenis_lokasi cascade;

-- ---------- tipe enum ----------
create type role_pengguna  as enum ('administrator', 'petugas');
create type status_akun    as enum ('aktif', 'nonaktif');
create type tahap_perkara  as enum ('lidik', 'sidik');
create type kondisi_barang as enum ('baik', 'rusak_ringan', 'rusak_berat');
create type status_barang  as enum ('tersedia', 'dipinjam', 'dalam_pemeriksaan', 'dihancurkan');
create type jenis_riwayat  as enum ('penerimaan', 'perpindahan', 'peminjaman', 'pengembalian', 'pemeriksaan', 'pengalihan');
create type status_kembali as enum ('belum_kembali', 'sudah_kembali');
create type jenis_lokasi   as enum ('penyimpanan', 'pemeriksaan', 'pemusnahan');

-- ---------- pengguna (profil; kata sandi dikelola Supabase Auth) ----------
create table pengguna (
  id              bigint generated by default as identity primary key,
  auth_id         uuid unique references auth.users(id) on delete set null,  -- akun login Supabase Auth
  username        varchar(30)  not null unique check (username ~ '^[a-z0-9._]{3,30}$'),
  nama            varchar(100) not null,
  pangkat         varchar(20),
  nrp             char(8) unique check (nrp ~ '^[0-9]{8}$'),
  jabatan         varchar(100) not null,
  role            role_pengguna not null default 'petugas',
  status          status_akun   not null default 'aktif',
  terakhir_login  timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ---------- master data ----------
create table kategori (
  id          bigint generated by default as identity primary key,
  kode        varchar(50)  not null unique,
  nama        varchar(100) not null unique,
  keterangan  text not null default ''
);

create table lokasi_penyimpanan (
  id          bigint generated by default as identity primary key,
  nama        varchar(100) not null unique,
  jenis       jenis_lokasi not null default 'penyimpanan',
  keterangan  text not null default ''
);

-- ---------- perkara ----------
create table perkara (
  id               bigint generated by default as identity primary key,
  nomor_lp         varchar(60) not null,
  tanggal_laporan  date not null,
  uraian           text not null,
  tahap            tahap_perkara not null,
  penyidik_id      bigint not null references pengguna(id),
  created_by       bigint references pengguna(id),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  deleted_at       timestamptz                            -- soft delete
);
create unique index perkara_nomor_lp_aktif on perkara (lower(nomor_lp)) where deleted_at is null;

-- ---------- barang bukti ----------
create table barang_bukti (
  id                   bigint generated by default as identity primary key,
  kode                 varchar(20) not null unique check (kode ~ '^BB-[0-9]{4}-[0-9]{4,}$'),
  nama                 varchar(150) not null,
  kategori_id          bigint not null references kategori(id),
  deskripsi            text not null default '',
  nomor_seri           varchar(100) not null default '',
  kondisi              kondisi_barang not null,
  perkara_id           bigint not null references perkara(id),
  tanggal_penerimaan   date not null,
  petugas_penerima_id  bigint not null references pengguna(id),
  lokasi_id            bigint not null references lokasi_penyimpanan(id),
  status               status_barang not null default 'tersedia',
  catatan              text not null default '',
  is_draf              boolean not null default false,
  created_by           bigint references pengguna(id),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  deleted_at           timestamptz                        -- soft delete; kode tidak dipakai ulang
);
create index barang_bukti_perkara on barang_bukti (perkara_id);

-- ---------- riwayat (append-only) ----------
create table riwayat_barang_bukti (
  id                       bigint generated by default as identity primary key,
  barang_bukti_id          bigint not null references barang_bukti(id),
  jenis                    jenis_riwayat not null,
  tanggal_waktu            timestamptz not null,
  lokasi_asal_id           bigint references lokasi_penyimpanan(id),  -- null = Penyerahan Penyidik
  lokasi_tujuan_id         bigint not null references lokasi_penyimpanan(id),
  petugas_id               bigint not null references pengguna(id),
  alasan                   varchar(255) not null,
  catatan                  text not null default '',
  tanggal_harapan_kembali  date,
  status_kembali           status_kembali,
  dicatat_oleh             bigint references pengguna(id),
  created_at               timestamptz not null default now(),
  constraint peminjaman_wajib_tanggal check (
    (jenis = 'peminjaman' and tanggal_harapan_kembali is not null and status_kembali is not null)
    or (jenis <> 'peminjaman' and tanggal_harapan_kembali is null and status_kembali is null)
  )
);
create index riwayat_barang on riwayat_barang_bukti (barang_bukti_id, tanggal_waktu desc);

-- Riwayat tidak boleh diubah atau dihapus, kecuali menandai peminjaman "sudah_kembali"
create or replace function riwayat_append_only() returns trigger language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'Riwayat barang bukti tidak boleh dihapus';
  end if;
  if (to_jsonb(new) - 'status_kembali') <> (to_jsonb(old) - 'status_kembali')
     or not (old.status_kembali = 'belum_kembali' and new.status_kembali = 'sudah_kembali') then
    raise exception 'Riwayat barang bukti tidak boleh diubah';
  end if;
  return new;
end $$;
create trigger riwayat_append_only before update or delete on riwayat_barang_bukti
  for each row execute function riwayat_append_only();

-- ---------- lampiran ----------
create table lampiran (
  id               bigint generated by default as identity primary key,
  barang_bukti_id  bigint not null references barang_bukti(id),
  nama_file        varchar(255) not null,
  tipe_mime        varchar(100) not null,
  ukuran_byte      integer not null check (ukuran_byte between 0 and 10485760),
  path             varchar(255) not null,                 -- path di bucket Storage "lampiran"
  diunggah_oleh    bigint references pengguna(id),
  created_at       timestamptz not null default now()
);
create index lampiran_barang on lampiran (barang_bukti_id);

-- ---------- updated_at otomatis ----------
create or replace function set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger pengguna_updated before update on pengguna for each row execute function set_updated_at();
create trigger perkara_updated before update on perkara for each row execute function set_updated_at();
create trigger barang_updated before update on barang_bukti for each row execute function set_updated_at();
